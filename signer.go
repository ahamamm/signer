package main

import (
	"bytes"
	"fmt"
	"os"
	arbsig "signer/JSR105Signer"
	// replace with your actual module path)
)

func main() {
	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	// 1️⃣ Load the source XML (could be any io.Reader – file, HTTP body, etc.)
	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	src, err := os.Open("tst.xml")
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot open source XML: %v\n", err)
		os.Exit(1)
	}
	defer src.Close()

	// Capture the signed output in memory (could be a file, DB, etc.)
	var signed bytes.Buffer

	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	// 2️⃣ Call the helper – the localPart below is the XML element you want to sign.
	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	if err := arbsig.TestSignatureUsingJSR105(src, &signed, "Message"); err != nil {
		fmt.Fprintf(os.Stderr, "signing error: %v\n", err)
		os.Exit(1)
	}

	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	// 3️⃣ Persist the signed document
	// ­‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑‑
	if err := os.WriteFile("sample-signed.xml", signed.Bytes(), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "cannot write signed XML: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("✅ Signed XML written to sample‑signed.xml")
}
